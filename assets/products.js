// Price label used on cards: "від 1 000 грн", "1 000 грн" or "ціна за запитом"
window.NANA.priceLabel = function (p) {
  if (p.price == null) return 'ціна за запитом';
  const from = p.options?.values.some((v) => v.price && v.price !== p.price) ? 'від ' : '';
  return from + p.price.toLocaleString('uk-UA') + ' грн';
};
// ids by type, in catalogue order
window.NANA.byType = function (t) { return Object.keys(this.products).filter((id) => !t || this.products[id].type === t); };

